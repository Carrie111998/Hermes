"""Tests for per-channel model and system prompt overrides (Fixes #1955)."""

from unittest.mock import patch

import pytest

from gateway.config import (
    ChannelOverride,
    GatewayConfig,
    Platform,
    PlatformConfig,
)
from gateway.run import _get_channel_override, GatewayRunner
from gateway.session import SessionSource


class TestGetChannelOverride:


    def test_no_override_when_channel_not_in_overrides(self):
        config = GatewayConfig(
            platforms={
                Platform.DISCORD: PlatformConfig(
                    enabled=True,
                    channel_overrides={
                        "999": ChannelOverride(model="openrouter/healer-alpha"),
                    },
                ),
            },
        )
        assert _get_channel_override(config, Platform.DISCORD, "123") is None

    def test_returns_override_when_channel_matches(self):
        ov = ChannelOverride(
            model="openrouter/healer-alpha",
            provider="openrouter",
            system_prompt="You are a summarizer.",
        )
        config = GatewayConfig(
            platforms={
                Platform.DISCORD: PlatformConfig(
                    enabled=True,
                    channel_overrides={"1234567890": ov},
                ),
            },
        )
        result = _get_channel_override(config, Platform.DISCORD, "1234567890")
        assert result is not None
        assert result.model == "openrouter/healer-alpha"
        assert result.provider == "openrouter"
        assert result.system_prompt == "You are a summarizer."


    def test_thread_id_lookup_when_chat_id_misses(self):
        config = GatewayConfig(
            platforms={
                Platform.DISCORD: PlatformConfig(
                    enabled=True,
                    channel_overrides={
                        "thread_99": ChannelOverride(model="topic-model"),
                    },
                ),
            },
        )
        result = _get_channel_override(
            config, Platform.DISCORD, "parent_chan", thread_id="thread_99"
        )
        assert result is not None
        assert result.model == "topic-model"

    def test_platform_wide_default_applies_when_no_specific_entry(self):
        """A ``"default"`` key applies to any channel with no specific entry."""
        config = GatewayConfig(
            platforms={
                Platform.MATRIX: PlatformConfig(
                    enabled=True,
                    channel_overrides={
                        "default": ChannelOverride(
                            model="stealth/ox-alpha", provider="openrouter"
                        ),
                    },
                ),
            },
        )
        result = _get_channel_override(config, Platform.MATRIX, "!unlisted:server")
        assert result is not None
        assert result.model == "stealth/ox-alpha"
        assert result.provider == "openrouter"

    def test_specific_entry_wins_over_platform_wide_default(self):
        """A chat_id/thread_id/parent_id entry always beats ``"default"``."""
        config = GatewayConfig(
            platforms={
                Platform.MATRIX: PlatformConfig(
                    enabled=True,
                    channel_overrides={
                        "default": ChannelOverride(model="cheap-default"),
                        "!vip:server": ChannelOverride(model="premium-model"),
                    },
                ),
            },
        )
        # Specific chat_id hits its own entry, not "default".
        specific = _get_channel_override(config, Platform.MATRIX, "!vip:server")
        assert specific is not None
        assert specific.model == "premium-model"
        # An unlisted chat_id falls through to "default".
        fallback = _get_channel_override(config, Platform.MATRIX, "!other:server")
        assert fallback is not None
        assert fallback.model == "cheap-default"

    def test_no_default_key_still_returns_none(self):
        """Without a ``"default"`` key, an unlisted channel returns None."""
        config = GatewayConfig(
            platforms={
                Platform.MATRIX: PlatformConfig(
                    enabled=True,
                    channel_overrides={
                        "!vip:server": ChannelOverride(model="premium-model"),
                    },
                ),
            },
        )
        assert _get_channel_override(config, Platform.MATRIX, "!other:server") is None


